const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
(async()=>{
  const browser = await chromium.launch({headless:true, ...(process.env.BROWSER_CHANNEL ? {channel:process.env.BROWSER_CHANNEL} : {})});
  const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const loadImages = () => page.locator('.exercise-card img').evaluateAll(async imgs => {
    for (const img of imgs) img.loading = 'eager';
    await Promise.all(imgs.map(img => img.decode()));
  });
  await page.goto(process.env.SITE_URL || 'http://127.0.0.1:4173',{waitUntil:'networkidle'});
  await page.evaluate(()=>document.fonts.ready);
  await loadImages();
  await fs.mkdir('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
  assert.equal(await page.locator('.exercise-card').count(),5);
  await page.getByRole('button',{name:'Приседание до стула, подход 1',exact:true}).click();
  await page.getByRole('button',{name:'Приостановить таймер',exact:true}).click();
  const paused = await page.locator('#timer-value').textContent();
  await page.waitForTimeout(1100);
  assert.equal(await page.locator('#timer-value').textContent(), paused);
  await page.reload();
  assert.equal(await page.getByRole('button',{name:'Приседание до стула, подход 1',exact:true}).getAttribute('aria-pressed'),'true');
  await page.locator('#tab-2').click();
  assert.equal(await page.locator('.set-button[aria-pressed=true]').count(),0);
  assert.match(await page.locator('#day-panel').innerText(),/Наклон с гантелями/);
  await page.locator('#tab-3').click();
  assert.match(await page.locator('#day-panel').innerText(),/Сгибание рук/);
  await page.locator('#tab-1').click();
  await page.selectOption('#mode','regular');
  assert.equal(await page.locator('.set-button').count(),10);
  assert.equal(await page.locator('.set-button[aria-pressed=true]').count(),0);
  await page.selectOption('#mode','easy');
  assert.equal(await page.locator('.set-button[aria-pressed=true]').count(),1);
  while(await page.locator('.set-button[aria-pressed=false]').count()) await page.locator('.set-button[aria-pressed=false]').first().click();
  await page.getByRole('button',{name:'Завершить тренировку',exact:false}).click();
  assert.match(await page.locator('#session-card').innerText(),/Вы сделали это/);
  assert.equal(await page.locator('.set-button:disabled').count(),5);
  await page.reload();
  assert.match(await page.locator('#session-card').innerText(),/Вы сделали это/);
  page.once('dialog',d=>d.dismiss());
  await page.getByRole('button',{name:'Начать этот день заново',exact:false}).click();
  assert.equal(await page.locator('.set-button[aria-pressed=true]').count(),5);
  page.once('dialog',d=>d.accept());
  await page.getByRole('button',{name:'Начать этот день заново',exact:false}).click();
  assert.equal(await page.locator('.set-button[aria-pressed=true]').count(),0);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('juligym:v1')).history.length),1);
  await page.getByRole('button',{name:'Как заниматься',exact:false}).click();
  assert.equal(await page.locator('#guide-dialog').evaluate(el=>el.open),true);
  await page.keyboard.press('Escape');
  await page.locator('.exercise-visual').first().click();
  assert.equal(await page.locator('#image-dialog').evaluate(el=>el.open),true);
  await page.getByRole('button',{name:'Движение',exact:true}).click();
  assert.equal(await page.locator('#image-stage').evaluate(el=>el.classList.contains('zoomed')),true);
  assert.match(await page.locator('#large-image').getAttribute('style'),/translateX/);
  await page.getByRole('button',{name:'Все фазы',exact:true}).click();
  assert.equal(await page.locator('#image-stage').evaluate(el=>el.classList.contains('zoomed')),false);
  await page.keyboard.press('Escape');
  await page.locator('#tab-1').focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('#tab-2').getAttribute('aria-selected'),'true');
  await page.locator('#tab-1').click();
  for (const width of [390,320,768]) {
    await page.setViewportSize({width,height:844});
    for(const day of [1,2,3]) {
      await page.locator(`#tab-${day}`).click();
      await loadImages();
      const overflow = await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
      assert.equal(overflow,false,`Overflow at ${width}, day ${day}`);
      await page.evaluate(()=>window.scrollTo(0,0));
      await page.screenshot({path:`artifacts/mobile-${width}-day${day}.png`,fullPage:true});
    }
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#tab-1').click();
  await page.evaluate(()=>{localStorage.removeItem('juligym:v1');});
  await page.reload();
  await loadImages();
  await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
  await page.evaluate(()=>window.dispatchEvent(new Event('beforeprint')));
  await page.locator('#print-area img').evaluateAll(imgs=>Promise.all(imgs.map(i=>i.decode())));
  await page.emulateMedia({media:'print'});
  await page.pdf({path:'artifacts/three-days.pdf',format:'A4',printBackground:true});
  assert.equal(await page.locator('.print-exercise').count(),15);
  assert.deepEqual(errors,[]);
  // Storage can be unavailable or contain data from an older version.
  const blocked=await browser.newContext();
  await blocked.addInitScript(()=>Object.defineProperty(window,'localStorage',{get(){throw new DOMException('blocked','SecurityError');}}));
  const blockedPage=await blocked.newPage();
  await blockedPage.goto(process.env.SITE_URL || 'http://127.0.0.1:4173');
  await blockedPage.locator('.set-button').first().click();
  assert.equal(await blockedPage.locator('.set-button').first().getAttribute('aria-pressed'),'true');
  await browser.close();
  console.log('PASS: navigation, independent modes/days, persistence, completion, reset, timer pause, dialogs, keyboard, 320/390/768px layouts, print, blocked storage.');
})().catch(e=>{console.error(e);process.exit(1);});
