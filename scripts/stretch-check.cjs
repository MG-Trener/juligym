const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL || 'msedge'});
 try{
  const page=await browser.newPage({viewport:{width:1800,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.SITE_URL || 'http://127.0.0.1:4173',{waitUntil:'networkidle'});
  const saved=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('juligym:v1')));
  await page.locator('[data-library-mode=stretch]').click();
  assert.equal(await page.locator('.library-group').count(),7);
  assert.equal(await page.locator('.library-item').count(),10);
  assert.equal(await page.locator('.recommendation').count(),3);
  await page.locator('#library-search').fill('бицепс');
  assert.equal(await page.locator('.library-item').count(),1);
  await page.locator('.library-item').click();
  await page.locator('.library-preview-image').click();
  await page.getByRole('button',{name:'Удержание',exact:true}).click();
  assert.ok(await page.locator('#image-stage').evaluate(e=>e.classList.contains('zoomed')));
  await page.keyboard.press('Escape');
  // Complete strength first: adding stretches afterwards must preserve it.
  while(await page.locator('[data-set][aria-pressed=false]').count())await page.locator('[data-set][aria-pressed=false]').first().click();
  await page.locator('#finish-session').click();
  const finished=(await saved()).sessions['1:easy'];
  await page.locator('#add-stretch-recommendations').click();
  assert.equal(await page.locator('.stretch-card').count(),3);
  let data=await saved();
  assert.equal(data.plans[0].items.length,5);assert.equal(data.history.length,1);
  assert.deepEqual(data.sessions['1:easy'].done,finished.done);assert.equal(data.sessions['1:easy'].finished,true);
  assert.equal(await page.locator('[data-set]:disabled').count(),5);
  const first=data.plans[0].stretches[0];
  await page.locator(`[data-stretch-done=${first}]`).click();
  await page.reload();
  assert.equal(await page.locator(`[data-stretch-done=${first}]`).getAttribute('aria-pressed'),'true');
  assert.equal((await saved()).sessions['1:easy'].finished,true);
  await page.selectOption('#mode','regular');
  assert.equal(await page.locator('[data-stretch-done][aria-pressed=true]').count(),0);
  await page.selectOption('#mode','easy');
  assert.equal(await page.locator('[data-stretch-done][aria-pressed=true]').count(),1);
  await page.locator('#tab-2').click();assert.equal(await page.locator('.stretch-card').count(),0);
  await page.locator('#tab-1').click();assert.equal(await page.locator('.stretch-card').count(),3);
  await page.locator(`[data-stretch-timer=${first}]`).click();
  assert.equal(await page.locator('#timer-value').innerText(),'00:20');
  assert.equal(await page.locator('#timer').getAttribute('aria-label'),'Таймер растяжки');
  await page.locator('[data-seconds="30"]').click();
  await page.locator('#timer-toggle').click();
  const paused=await page.locator('#timer-value').innerText();await page.waitForTimeout(1100);
  assert.equal(await page.locator('#timer-value').innerText(),paused);
  await page.locator('#timer-toggle').click();assert.match(await page.locator('#timer-label').innerText(),/РАСТЯЖКА/);
  await page.locator('#timer-close').click();
  await page.locator('[data-rest]').first().click();
  assert.equal(await page.locator('#timer').getAttribute('aria-label'),'Таймер отдыха');
  assert.equal(await page.locator('[data-seconds="90"]').count(),1);
  await page.locator('#timer-close').click();
  await page.evaluate(()=>window.dispatchEvent(new Event('beforeprint')));
  assert.equal(await page.locator('.print-stretches').count(),1);
  assert.equal(await page.locator('.print-stretches .print-exercise').count(),3);
  await page.locator(`[data-remove-stretch=${first}]`).click();
  data=await saved();assert.equal(data.plans[0].stretches.length,2);assert.equal(data.sessions['1:easy'].finished,true);
  assert.deepEqual(data.sessions['1:easy'].stretchDone,[]);
  await page.locator('[data-stretch-done]').first().click();
  page.once('dialog',d=>d.accept());await page.locator('#new-session').click();
  assert.equal(await page.locator('[data-stretch-done][aria-pressed=true]').count(),0);
  assert.equal((await saved()).history.length,1);
  await fs.mkdir('artifacts',{recursive:true});
  for(const width of [1800,1440,1024,768,390,320]){
   await page.setViewportSize({width,height:950});
   await page.locator('.stretch-card img').evaluateAll(async imgs=>{imgs.forEach(i=>i.loading='eager');await Promise.all(imgs.map(i=>i.decode()));});
   await page.locator('#stretch-section').scrollIntoViewIfNeeded();
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`Stretch overflow ${width}`);
   await page.screenshot({path:`artifacts/stretch-${width}.png`});
   await page.locator('#open-stretch-library').click();
   assert.equal(await page.locator('[data-library-mode=stretch]').getAttribute('aria-pressed'),'true');
   await page.screenshot({path:`artifacts/stretch-library-${width}.png`});
   if(width<=1000)await page.keyboard.press('Escape');
  }
  assert.deepEqual(errors,[]);
  console.log('PASS: stretch catalog, muscle recommendations, independent completion after strength, persistence, days/modes, removal/reset, timer, print, desktop and mobile.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
